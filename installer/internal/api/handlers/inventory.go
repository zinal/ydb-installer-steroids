// Package handlers contains the HTTP handler functions exposed by the
// installer's REST API.
package handlers

import (
	"encoding/json"
	"net/http"
	"os"
	"path/filepath"

	"ydb-installer/internal/models"
	"ydb-installer/internal/services/config"
	"ydb-installer/internal/services/session"
)

const inventoryPath = "inventory/50-inventory.yaml"

// Inventory handles GET/PUT /api/inventory.
//
//   - GET  → returns the current inventory data from the session.
//   - PUT  → applies inventory updates, writes to file, and updates session.
//     If 90-inventory exists, also patches ydb_em_az_locations.
func Inventory(store *session.Store, writer *config.InventoryWriter, emWriter *config.EMInventoryWriter, emInvPath string) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		switch r.Method {
		case http.MethodGet:
			inv := store.GetInventory()
			writeJSON(w, http.StatusOK, map[string]interface{}{
				"inventory_found": store.Get().InventoryFound,
				"config_found":    store.Get().ConfigFound,
				"data":            inv,
			})

		case http.MethodPut:
			var data models.InventoryData
			if err := json.NewDecoder(r.Body).Decode(&data); err != nil {
				writeError(w, http.StatusBadRequest, "invalid JSON: "+err.Error())
				return
			}

			// Preserve backend-managed fields that the frontend does not send.
			// The UI does not manage dynamic_nodes — keep existing values to
			// prevent the inventory writer from overwriting them with defaults.
			if len(data.DynamicNodes) == 0 {
				if existing := store.GetInventory(); existing != nil {
					data.DynamicNodes = existing.DynamicNodes
				}
			}

			// Use WriteWithPatch to preserve user's existing inventory content
			// (comments, unknown vars, structure). Falls back to fresh build
			// if the file doesn't exist yet.
			cwd, _ := os.Getwd()
			fullPath := filepath.Join(cwd, inventoryPath)
			if err := writer.WriteWithPatch(fullPath, &data); err != nil {
				writeError(w, http.StatusInternalServerError, "failed to write inventory: "+err.Error())
				return
			}

			// Re-parse inventory to get updated DynamicNodes (ydb_dynnodes)
			// generated by buildDynamicNodes during WriteWithPatch.
			// This keeps the session in sync with the file, preventing stale
			// DynamicNodes from blocking instance letters on subsequent writes.
			invService := config.NewInventoryService()
			if parsed, err := invService.Parse(fullPath); err == nil && len(parsed.DynamicNodes) > 0 {
				data.DynamicNodes = parsed.DynamicNodes
			}

			// If 90-inventory exists, refresh ydb_em_az_locations from the DC hosts.
			if emWriter != nil && emInvPath != "" {
				azLocs := config.DeriveAZFromDCs(data.DC1, data.DC2, data.DC3)
				_ = emWriter.PatchAZLocations(emInvPath, azLocs)
			}

			store.UpdateInventory(&data, true, true)

			writeJSON(w, http.StatusOK, map[string]interface{}{
				"status": "ok",
				"data":   store.GetInventory(),
			})

		default:
			w.Header().Set("Allow", "GET, PUT")
			writeError(w, http.StatusMethodNotAllowed, "method not allowed")
		}
	}
}
